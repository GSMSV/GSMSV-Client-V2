export type OcticonName = keyof typeof icons;
export const octiconNames = Object.keys(icons) as OcticonName[];

export type OcticonProps = Omit<IconProps, 'size'> & {
  name: OcticonName;
  size?: number;
};

export function Octicon({ name, size = 16, 'aria-label': ariaLabel, ...props }: OcticonProps) {
  const IconComponent = icons[name];

  return (
    <IconComponent
      aria-label={ariaLabel}
      size={size}
      {...props}
    />
  );
}
